export function buildIntro(template: LegalTemplate): string[] {
  const paragraphs: string[] = [];

  paragraphs.push(template.description);

  paragraphs.push(
    `Правовая основа — ${template.actSource}. Документ составлен с учётом актуальных требований законодательства РФ на ${template.lastUpdated.toLowerCase()}. Для сделок, не требующих обязательного нотариального удостоверения, достаточно простой письменной формы (ст. 161 ГК РФ): распечатайте документ и подпишите его обеими сторонами.`
  );

  const fieldCats = [...new Set(template.fields.map((f) => f.category))].filter(
    (c) => FIELD_CATEGORY_LABELS[c]
  );
  if (fieldCats.length > 0) {
    const parts = fieldCats
      .slice(0, 5)
      .map((c) => FIELD_CATEGORY_LABELS[c]);
    paragraphs.push(
      `Форма включает: ${parts.join(", ")}${fieldCats.length > 5 ? " и другое" : ""}. Все поля проверяются автоматически: сервис подсветит незаполненные обязательные поля и ошибки формата, а сумму в рублях пропишет словами.`
    );
  }

  const peculiar = CATEGORY_PECULIAR[template.category];
  if (peculiar) paragraphs.push(peculiar);

  paragraphs.push(
    `Составьте документ онлайн за 5 минут бесплатно: заполните форму, проверьте готовый документ в предпросмотре и скачайте его в PDF или DOCX. Данные обрабатываются только в вашем браузере и не передаются на сервер.`
  );

  return paragraphs;
}

export function fieldsSummary(template: LegalTemplate): string[] {
  const grouped = new Map<string, string[]>();
  for (const f of template.fields) {
    const label = FIELD_CATEGORY_LABELS[f.category] || "прочие данные";
    const arr = grouped.get(label);
    if (arr) arr.push(f.label);
    else grouped.set(label, [f.label]);
  }
  return [...grouped.entries()].map(
    ([cat, labels]) => `${cat[0].toUpperCase()}${cat.slice(1)}: ${labels.join(", ")}.`
  );
}