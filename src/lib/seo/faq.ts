/**
 * Пер-документный FAQ: 4 вопроса, два из которых уникальны для каждого
 * шаблона (состав полей и правовое основание). Используется на страницах
 * /documents/{id} и /blanks/{id}.
 */
export function faqForDocument(t: LegalTemplate): FaqItem[] {
  const labels = t.fields
    .filter((f) => f.type !== "repeating")
    .map((f) => f.label)
    .slice(0, 6);
  const fieldsText =
    labels.length > 0 ? labels.join(", ") : "данные сторон и условия документа";

  // Заявления: нотариус не нужен никогда (одностороннее обращение),
  // вместо категории — ответ про подачу из submitTo. Имена шаблонов уникальны
  // (проверяется тестами), поэтому имя + маршрут подачи дают уникальные ответы.
  if (t.kind === "statement") {
    const where = t.submitTo?.where ?? "в соответствующий орган";
    const route = t.submitTo
      ? `Срок: ${t.submitTo.term}. Пошлина: ${t.submitTo.fee}. Приложить: ${t.submitTo.attach}.`
      : "";
    return [
      {
        q: `Какие данные нужны, чтобы заполнить «${t.name}»?`,
        a: `Для «${t.name}» понадобятся: ${fieldsText}. Подача: ${where}. ${route} Обязательные поля сервис проверит автоматически, заполнение занимает около 5 минут.`.trim(),
      },
      {
        q: `Куда подавать «${t.name}»?`,
        a: `«${t.name}» подаётся: ${where}. ${route}`.trim(),
      },
      {
        q: `На основании какого закона составлен «${t.name}»?`,
        a: `Правовая основа «${t.name}» — ${t.actSource}. Шаблон составлен по актуальным требованиям законодательства РФ (обновлён ${t.lastUpdated.toLowerCase()}).`,
      },
      {
        q: `Можно ли скачать «${t.name}» бесплатно в Word и PDF?`,
        a: `Да. Заявление заполняется онлайн и скачивается в PDF и DOCX бесплатно, без регистрации. Данные обрабатываются в вашем браузере и не передаются на сервер.`,
      },
    ];
  }

  return [
    {
      q: `Какие данные нужны, чтобы заполнить «${t.name}»?`,
      a: `Для «${t.name}» понадобятся: ${fieldsText}. Обязательные поля сервис проверит автоматически, а сумму в рублях пропишет словами — заполнение занимает около 5 минут.`,
    },
    {
      q: `На основании какого закона составлен «${t.name}»?`,
      a: `Правовая основа «${t.name}» — ${t.actSource}. Шаблон составлен по актуальным требованиям законодательства РФ (обновлён ${t.lastUpdated.toLowerCase()}).`,
    },
    {
      q: `Нужно ли заверять «${t.name}» у нотариуса?`,
      a: CATEGORY_NOTARY[t.category] || CATEGORY_NOTARY.other,
    },
    {
      q: `Можно ли скачать «${t.name}» бесплатно в Word и PDF?`,
      a: `Да. Документ заполняется онлайн и скачивается в PDF и DOCX бесплатно, без регистрации. Данные обрабатываются в вашем браузере и не передаются на сервер.`,
    },
  ];
}

export function faqJsonLd(faq: FaqItem[]) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faq.map((f) => ({
      "@type": "Question",
      name: f.q,
      acceptedAnswer: { "@type": "Answer", text: f.a },
    })),
  };
}

export function breadcrumbJsonLd(items: { name: string; path: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map((it, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: it.name,
      item: `https://dogovor.expert${it.path}`,
    })),
  };
}