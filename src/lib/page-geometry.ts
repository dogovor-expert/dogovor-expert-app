/**
 * Геометрия страницы и измерение текста — единый источник для всех движков
 * документов (PDF и DOCX).
 *
 * ⚠️ До 30.09.2026 константа A4 была продублирована в пяти файлах
 * (docDesign, exportPdf, exportDocx, exportDocxLazy, resume/resumePdf), а
 * измерение текста реализовано трижды (measureText, splitTextIntoLines и
 * своя версия в резюме). Именно из-за этого приходилось вручную
 * синхронизировать геометрию, а расхождения проявлялись как «в одном
 * месте поправил — в другом сломал» (например, отступы шаблонов резюме).
 *
 * Единицы:
 *  - PDF: пункты (pt), 1 мм = 72/25.4 pt
 *  - DOCX: твипы (twips), 1 мм = 56.6929134 twips
 */

/** Точки на миллиметр. */
export const PT_PER_MM = 72 / 25.4;
/** Твипы на миллиметр (1440 twips = 1 дюйм). */
export const TWIPS_PER_MM = 1440 / 25.4;

/** A4 в пунктах — базовая геометрия страницы. */
export const A4_PT = { w: 595.28, h: 841.89 } as const;

/**
 * A4 в миллиметрах — ISO 216. Нужен DOCX-движкам: там ширина считается в
 * твипах, и раньше она выводилась из пунктов двойным преобразованием
 * (`595.28 * 20`), где «* 20» — это руками вписанный перевод pt → twips.
 * Держим оба значения явно, чтобы связь была видна кодом.
 */
export const A4_MM = { w: 210, h: 297 } as const;

export const mmToPt = (mm: number): number => mm * PT_PER_MM;
export const mmToTwips = (mm: number): number => Math.round(mm * TWIPS_PER_MM);

