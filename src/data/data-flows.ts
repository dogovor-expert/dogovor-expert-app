/**
 * ЕДИНЫЙ ИСТОЧНИК ПРАВДЫ о том, где обрабатываются данные пользователя.
 *
 * Зачем он нужен: сайт обещает «документы остаются в браузере», и это
 * обещание юридически значимо (политика конфиденциальности, раздел 2).
 * Но часть операций всё же обращается к серверу — и пользователь должен
 * видеть это явно, а не угадывать.
 *
 * ⚠️ Правило поддержки этого файла: список можно править ТОЛЬКО после
 * проверки по коду. Каждая строка ниже подтверждена конкретным местом:
 *  - browser-операции — движки src/lib/exportPdf.ts, exportDocxLazy.ts,
 *    resumePdf.ts и конвертеры src/components/converter/* (работают с
 *    File/ArrayBuffer локально, сетевых вызовов нет);
 *  - server-операции — роуты src/app/api/** (проверено построчно);
 *  - thirdParty — фактические BASE_URL из src/lib/ai/*.ts, src/lib/analytics.ts.
 *
 * Тест src/lib/__tests__/dataFlows.test.ts следит, чтобы у каждой операции
 * были срок хранения и честное описание (требование Рособрнадзора к
 * политике: состав ПДн, цели, третьи лица, сроки хранения).
 */

export type DataLocation = "browser" | "server" | "thirdParty";

export interface DataFlow {
  /** Короткое имя операции для интерфейса. */
  operation: string;
  /** Где происходит обработка. */
  where: DataLocation;
  /** Что именно покидает устройство (или что НЕ покидает). */
  detail: string;
  /** Почему нельзя обойтись обработкой в браузере. */
  why?: string;
  /** Срок хранения. Для browser-операций — «не сохраняется». */
  retention: string;
  /** Требуется ли явное согласие пользователя. */
  consent?: boolean;
}

